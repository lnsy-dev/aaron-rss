/**
 * Feed Not Recognized Regression Tests
 *
 * Sites behind bot checks and error pages answer HTTP 200 with an HTML
 * page, and a few real feeds carry an <rss> root whose version attribute
 * is missing or unusual (some generators emit version="1.1"). Both used
 * to land in rss-parser and surface as the same cryptic console error —
 * "Feed not recognized as RSS 1 or 2." — logged by
 * src/lib/rss-parser.js (parseFeedText's catch).
 *
 * These tests pin the new behavior: versionless and unusual-version RSS
 * documents parse, HTML pages are rejected up front with a message that
 * names the real cause, and every previously working feed shape still
 * parses.
 */

import { describe, it, expect, vi, afterEach } from 'vitest';
import { parseFeedText } from '../../src/lib/rss-parser.js';

const FEED_URL = 'https://example.com/feed.xml';

afterEach(() => {
  vi.restoreAllMocks();
});

describe('unusual RSS roots parse', () => {
  it('parses an <rss> document with no version attribute', async () => {
    const rss = `<?xml version="1.0"?>
      <rss>
        <channel>
          <title>Versionless Feed</title>
          <link>https://example.com</link>
          <item><title>Item One</title><link>https://example.com/1</link></item>
        </channel>
      </rss>`;

    const feed = await parseFeedText(rss, FEED_URL);

    expect(feed).not.toBeNull();
    expect(feed.title).toBe('Versionless Feed');
    expect(feed.items).toHaveLength(1);
    expect(feed.items[0].title).toBe('Item One');
  });

  it('parses an <rss> document with an unusual version attribute', async () => {
    const rss = `<?xml version="1.0"?>
      <rss version="1.1">
        <channel>
          <title>Odd Version Feed</title>
          <item><title>Item Two</title></item>
        </channel>
      </rss>`;

    const feed = await parseFeedText(rss, FEED_URL);

    expect(feed).not.toBeNull();
    expect(feed.title).toBe('Odd Version Feed');
    expect(feed.items).toHaveLength(1);
  });

  it('still parses a standard RSS 2.0 document the same way', async () => {
    const rss = `<?xml version="1.0"?>
      <rss version="2.0">
        <channel><title>Standard</title><item><title>i</title></item></channel>
      </rss>`;

    const feed = await parseFeedText(rss, FEED_URL);

    expect(feed).not.toBeNull();
    expect(feed.title).toBe('Standard');
  });
});

describe('HTML responses are rejected with the real cause', () => {
  it('returns null for a bot-check style HTML page', async () => {
    const html = `<!doctype html>
      <html><head><title>Just a moment...</title></head>
      <body>Checking your browser before accessing example.com</body></html>`;

    const feed = await parseFeedText(html, FEED_URL);

    expect(feed).toBeNull();
  });

  it('returns null for an HTML page that merely mentions <rss in its text', async () => {
    // The old substring-based detection classified this as RSS and died
    // inside the XML parser with an unrelated syntax error.
    const html = `<!doctype html>
      <html><body><p>We syndicate our news via &lt;rss&gt; files.</p></body></html>`;

    const feed = await parseFeedText(html, FEED_URL);

    expect(feed).toBeNull();
  });

  it('returns null for an XHTML page with no doctype', async () => {
    const html = '<html xmlns="http://www.w3.org/1999/xhtml"><body><p>login</p></body></html>';

    const feed = await parseFeedText(html, FEED_URL);

    expect(feed).toBeNull();
  });

  it('logs a message that names the HTML page instead of the rss-parser error', async () => {
    const errorSpy = vi.spyOn(console, 'error').mockImplementation(() => {});
    const html = '<!doctype html><html><body>challenge</body></html>';

    await parseFeedText(html, FEED_URL);

    expect(errorSpy).toHaveBeenCalledTimes(1);
    const message = errorSpy.mock.calls[0].join(' ');
    expect(message).toContain(FEED_URL);
    expect(message).toContain('HTML page, not a feed');
    expect(message).not.toContain('Feed not recognized as RSS 1 or 2');
  });
});

describe('prolog forms still parse', () => {
  it('parses a feed with a byte-order mark', async () => {
    const rss = '﻿<?xml version="1.0"?><rss version="2.0"><channel><title>BOM Feed</title></channel></rss>';

    const feed = await parseFeedText(rss, FEED_URL);

    expect(feed).not.toBeNull();
    expect(feed.title).toBe('BOM Feed');
  });

  it('parses a feed with comments and whitespace before the root', async () => {
    const rss = `
      <!-- generated by ExampleCMS -->
      <?xml version="1.0" encoding="UTF-8"?>
      <!-- another comment -->
      <rss version="2.0"><channel><title>Commented Feed</title></channel></rss>`;

    const feed = await parseFeedText(rss, FEED_URL);

    expect(feed).not.toBeNull();
    expect(feed.title).toBe('Commented Feed');
  });

  it('still parses an RSS 1.0 RDF document', async () => {
    const rdf = `<?xml version="1.0"?>
      <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"
               xmlns="http://purl.org/rss/1.0/">
        <channel><title>RDF Feed</title></channel>
        <item><title>RDF Item</title></item>
      </rdf:RDF>`;

    const feed = await parseFeedText(rdf, FEED_URL);

    expect(feed).not.toBeNull();
    expect(feed.items).toHaveLength(1);
    expect(feed.items[0].title).toBe('RDF Item');
  });

  it('returns null for genuinely malformed XML', async () => {
    const feed = await parseFeedText('not xml at all', FEED_URL);

    expect(feed).toBeNull();
  });
});
